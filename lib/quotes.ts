/** 문자열을 간단한 해시값(음수 없는 32bit 정수)으로 변환한다. */
function simpleHash(input: string): number {
  let hash = 0;
  for (let i = 0; i < input.length; i++) {
    hash = (hash * 31 + input.charCodeAt(i)) >>> 0;
  }
  return hash;
}

/** 오늘 날짜와 사용자 id를 조합해 오늘의 응원문구를 결정적으로 하나 선택한다. */
export function pickDailyQuote(dateStr: string, userId: string): string {
  const hash = simpleHash(`${dateStr}:${userId}`);
  return QUOTES[hash % QUOTES.length];
}
